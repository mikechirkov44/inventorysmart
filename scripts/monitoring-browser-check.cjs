const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
    page.setDefaultTimeout(7000);
    await page.clock.install({ time: new Date('2026-09-28T09:15:00Z') });
    const errors = []; const writes = [];
    page.on('pageerror', error => errors.push(error.message));
    const equipment = Array.from({ length: 32 }, (_, i) => ({ id: `equipment-${i}`, name: i === 0 ? 'Фрезерный станок Kutez FC7' : `Оборудование ${i}`, inventoryNumber: `ИТ-${100 + i}`, status: 'working', categoryName: i % 2 ? 'Печи' : 'Станки', roomName: i % 2 ? 'Лаборатория' : 'Цех литья', workIds: [] }));
    await page.addInitScript(() => localStorage.setItem('token', 'demo-test'));
    await page.route('**/api/**', async route => {
      const url = new URL(route.request().url()); let data = [];
      if (route.request().method() !== 'GET') writes.push(url.pathname);
      if (url.pathname === '/api/auth/me') data = { id: 'viewer', role: 'employee', permissions: { equipment: 'view' } };
      else if (url.pathname.includes('license')) data = { status: 'active' };
      else if (url.pathname === '/api/company') data = { companyName: 'Демонстрация' };
      else if (url.pathname === '/api/equipment') data = equipment;
      else if (url.pathname === '/api/equipment/equipment-0') data = equipment[0];
      else if (url.pathname.endsWith('/operating-hours')) data = { data: null };
      else if (url.pathname.endsWith('/qr')) data = null;
      await route.fulfill({ json: data });
    });
    await page.goto('http://127.0.0.1:5181/monitoring');
    await page.getByRole('heading', { name: 'Мониторинг', exact: true }).waitFor().catch(async error => { console.error(errors, await page.locator('body').innerText()); throw error; });
    assert.ok(await page.getByText('Демо-данные', { exact: true }).count());
    await page.locator('.monitor-table tbody tr').first().waitFor();
    const cell = page.locator('.monitor-table tbody tr').first().locator('button.monitor-load-cell').first();
    const value = await cell.getAttribute('data-utilization');
    await cell.click();
    const modal = page.getByRole('dialog');
    await modal.locator('.monitor-day-load').waitFor();
    assert.equal(await modal.locator('.monitor-day-load').getAttribute('data-utilization'), value);
    await modal.getByRole('button', { name: 'Дата мониторинга', exact: true }).click();
    await page.locator('.calendar-dropdown').getByRole('button', { name: '22', exact: true }).click();
    assert.ok((await modal.getByRole('link', { name: 'Карточка оборудования' }).getAttribute('href')).includes('2026-09-22'));
    await modal.getByRole('button', { name: 'Предыдущий день', exact: true }).click();
    await modal.getByRole('link', { name: 'Карточка оборудования' }).click();
    await page.locator('#equipment-monitoring .monitor-day-load').waitFor();
    assert.equal(await page.locator('#equipment-monitoring .monitor-day-load').getAttribute('data-utilization'), value);
    await page.goto('http://127.0.0.1:5181/monitoring');
    await page.getByPlaceholder('Название или инвентарный номер').fill('Kutez');
    assert.equal(await page.locator('.monitor-table tbody tr').count(), 1);
    await page.getByRole('button', { name: 'Сбросить', exact: true }).click();
    await page.getByRole('button', { name: 'Следующая страница' }).click();
    assert.equal(await page.locator('.monitor-table tbody tr').count(), 7);
    await page.getByRole('button', { name: 'Предыдущая страница' }).click();
    await page.screenshot({ path: 'tmp/monitoring-light.png', fullPage: true });
    await page.evaluate(() => document.documentElement.dataset.theme = 'dark'); await page.waitForTimeout(500);
    await page.screenshot({ path: 'tmp/monitoring-dark.png', fullPage: true });
    await page.locator('.monitor-load-cell').first().click(); await modal.locator('.monitor-day-load').waitFor();
    await page.screenshot({ path: 'tmp/monitoring-day-dark.png', fullPage: true });
    await page.keyboard.press('Escape'); assert.equal(await page.getByRole('dialog').count(), 0);
    await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(300);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'No document overflow on mobile');
    assert.deepEqual(writes, [], 'Demonstration must not write to production equipment');
    assert.deepEqual(errors, []);
    console.log('PASS: monitoring route, demo label, matrix/detail consistency, search, pagination, modal keyboard, themes, mobile, no writes');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
