const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const assert = require('node:assert/strict');
const { validateLayoutPayload } = require('../server/utils/equipmentMapValidation');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(() => {
      localStorage.setItem('token', 'test'); localStorage.setItem('equipment-view', 'map');
      // Reproduce HTTP deployment where randomUUID is unavailable.
      Object.defineProperty(crypto, 'randomUUID', { value: undefined });
    });
    const eq = '11111111-1111-4111-8111-111111111111';
    const extra = { id: '22222222-2222-4222-8222-222222222222', name: 'Насос', inventoryNumber: 'ИТ-002', status: 'reserve' };
    let failSave = false; let conflictSave = false; let delaySave = 0; let saveStarted = 0; let activeSaves = 0; let maxActiveSaves = 0;
    let layout = { id: 'floor', name: 'Этаж', canvasWidth: 1600, canvasHeight: 900, version: 0, elements: [], placements: [{ equipmentId: eq, x: 800, y: 400, width: 180, height: 80, equipment: { id: eq, name: 'Станок', status: 'working' } }] };
    await page.route('**/api/**', async route => {
      const path = new URL(route.request().url()).pathname;
      let data = {};
      if (path === '/api/auth/me') data = { id: 'tester', role: 'admin', permissions: { equipment: 'full' } };
      else if (path.includes('license')) data = { status: 'active' };
      else if (path.endsWith('/buildings')) data = [{ id: 'building', name: 'Здание', floors: [{ id: 'floor', name: 'Этаж' }] }];
      else if (path.endsWith('/layout')) {
        const payload = route.request().postDataJSON();
        validateLayoutPayload(payload, { width: 1600, height: 900 });
        saveStarted++; activeSaves++; maxActiveSaves = Math.max(maxActiveSaves, activeSaves);
        await new Promise(resolve => setTimeout(resolve, delaySave));
        activeSaves--;
        if (conflictSave) return route.fulfill({ status: 409, json: { error: 'План изменён другим пользователем' } });
        if (failSave) return route.fulfill({ status: 503, json: { error: 'Тест: временная ошибка соединения' } });
        assert.equal(payload.version, layout.version, 'Save uses latest version');
        layout = { ...layout, ...payload, version: layout.version + 1 }; data = { version: layout.version };
      }
      else if (path.endsWith('/floors/floor')) data = layout;
      else if (path.endsWith('/unplaced-equipment')) data = new URL(route.request().url()).searchParams.get('search') === 'Дальний' ? [{ id: '33333333-3333-4333-8333-333333333333', name: 'Дальний станок', status: 'working' }] : layout.placements.some(p => p.equipmentId === extra.id) ? [] : [extra];
      await route.fulfill({ json: data });
    });
    await page.goto('http://127.0.0.1:5173/equipment');
    await page.getByRole('button', { name: 'Редактировать', exact: true }).click();
    await page.getByRole('button', { name: 'Стена', exact: true }).click();
    const box = await page.locator('.map-canvas').boundingBox();
    const draw = async (x,y,dx,dy) => { await page.mouse.move(box.x+x,box.y+y); await page.mouse.down(); await page.mouse.move(box.x+x+dx,box.y+y+dy,{steps:8}); await page.mouse.up(); };
    await draw(80,100,180,0);
    await page.waitForTimeout(100);
    assert.equal(await page.locator('.map-wall').count(), 1, `Wall not created: ${errors.join('; ')}`);
    assert.equal(await page.getByRole('button', { name: 'Выбор', exact: true }).getAttribute('aria-pressed'), 'true', 'Return to selection after creating a wall');
    await page.getByRole('button', { name: 'Прямоугольник', exact: true }).click();
    await draw(90,200,200,130);
    assert.equal(await page.locator('.map-wall').count(), 5);
    await page.getByRole('button', { name: 'Метка', exact: true }).click();
    await page.mouse.click(box.x+350,box.y+150);
    const dialog = page.getByRole('dialog', { name: 'Новая метка' });
    assert.equal(await dialog.getByRole('button', { name: 'Добавить' }).isDisabled(), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.map-label').count(), 0);
    await page.mouse.click(box.x+350,box.y+150);
    await dialog.getByLabel('Название метки').fill('Цех литья');
    await dialog.getByRole('button', { name: 'Добавить' }).click();
    assert.equal(await page.locator('.map-label').textContent(), 'Цех литья');
    await page.locator('.map-equipment-card').click();
    const handle = await page.locator('.map-resize-handle[data-edge="se"]').boundingBox();
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
    await page.mouse.down();
    await page.mouse.move(handle.x + handle.width / 2 + 60, handle.y + handle.height / 2 + 40, { steps: 8 });
    await page.mouse.up();
    assert.ok(Number(await page.locator('.map-equipment-card').getAttribute('width')) > 180, 'Equipment should resize even after label tool was used');
    await page.getByRole('button', { name: 'Отменить', exact: true }).click();
    assert.equal(Number(await page.locator('.map-equipment-card').getAttribute('width')), 180, 'One undo reverts the entire drag');
    await page.getByRole('button', { name: 'Повторить', exact: true }).click();
    assert.ok(Number(await page.locator('.map-equipment-card').getAttribute('width')) > 180);
    const world = async (x, y) => page.locator('.map-canvas').evaluate((svg, p) => {
      const point = svg.createSVGPoint(); point.x = p.x; point.y = p.y;
      const result = point.matrixTransform(svg.getScreenCTM()); return { x: result.x, y: result.y };
    }, { x, y });
    const clickWorld = async (x, y) => { const p = await world(x, y); await page.mouse.click(p.x, p.y); };
    const dragWorld = async (x, y, endX, endY) => {
      const a = await world(x, y); const b = await world(endX, endY);
      await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 10 }); await page.mouse.up();
    };
    // Equipment can be selected from the sidebar and placed with a click.
    await page.getByRole('button', { name: /Насос.*ИТ-002/ }).click();
    await clickWorld(1000, 650);
    assert.equal(await page.locator('.map-equipment-card').count(), 2);
    await page.getByPlaceholder('Найти оборудование').fill('Дальний');
    await page.getByRole('button', { name: /Дальний станок/ }).waitFor({ timeout: 3000 });
    await page.getByPlaceholder('Найти оборудование').fill('');
    // Create a separate wall with two clicks, cut a gap and adjust its endpoint.
    await page.getByRole('button', { name: 'Стена', exact: true }).click();
    await clickWorld(100, 750); await clickWorld(700, 750);
    assert.equal(await page.locator('.map-wall').count(), 6);
    await clickWorld(200, 760);
    await page.getByRole('button', { name: 'Сделать проём' }).click();
    await clickWorld(300, 760); await clickWorld(420, 760);
    assert.equal(await page.locator('.map-wall').count(), 7);
    await clickWorld(180, 760);
    await dragWorld(100, 760, 60, 700);
    await page.getByRole('button', { name: 'Отменить', exact: true }).click();
    assert.equal(await page.locator('.map-wall[x1="100"][y1="760"]').count(), 1);
    await page.locator('.map-label').dblclick();
    const rename = page.getByRole('dialog', { name: 'Название метки', exact: true });
    await rename.getByLabel('Название метки').fill('Участок литья');
    await rename.getByRole('button', { name: 'Сохранить', exact: true }).click();
    assert.equal(await page.locator('.map-label').textContent(), 'Участок литья');
    await page.getByRole('button', { name: 'Стена', exact: true }).click();
    await clickWorld(1400, 100); await page.keyboard.press('Escape'); await clickWorld(1400, 200);
    assert.equal(await page.locator('.map-wall').count(), 7, 'Escape cancels unfinished wall');
    // View navigation must not modify the layout.
    const oldView = await page.locator('.map-canvas').getAttribute('viewBox');
    const center = await world(800, 450); await page.mouse.move(center.x, center.y); await page.mouse.wheel(0, -100); await page.waitForTimeout(100);
    assert.notEqual(await page.locator('.map-canvas').getAttribute('viewBox'), oldView);
    await page.keyboard.down('Space'); await page.mouse.down(); await page.mouse.move(center.x + 50, center.y + 40); await page.mouse.up(); await page.keyboard.up('Space');
    await page.getByTitle('Показать весь этаж').click();
    await page.waitForTimeout(1300);
    assert.equal(layout.elements.length, 8);
    // Keep newer edits while a previous save is in flight, then retry a failure.
    delaySave = 1200;
    const beforeSave = saveStarted;
    await page.getByRole('button', { name: 'Метка', exact: true }).click(); await clickWorld(1000, 200);
    await dialog.getByLabel('Название метки').fill('А'); await dialog.getByRole('button', { name: 'Добавить' }).click();
    for (let i = 0; saveStarted === beforeSave && i < 100; i++) await page.waitForTimeout(50);
    assert.ok(saveStarted > beforeSave, 'Autosave starts');
    await page.getByRole('button', { name: 'Метка', exact: true }).click(); await clickWorld(1100, 200);
    await dialog.getByLabel('Название метки').fill('Б'); await dialog.getByRole('button', { name: 'Добавить' }).click();
    await page.waitForTimeout(3300);
    assert.equal(layout.elements.length, 10); assert.equal(maxActiveSaves, 1);
    delaySave = 0; failSave = true;
    await page.getByRole('button', { name: 'Метка', exact: true }).click(); await clickWorld(1200, 200);
    await dialog.getByLabel('Название метки').fill('В'); await dialog.getByRole('button', { name: 'Добавить' }).click();
    await page.getByRole('button', { name: 'Повторить сохранение', exact: true }).waitFor();
    assert.equal(await page.locator('.map-label').count(), 4);
    assert.equal(await page.getByTitle('Таблица', { exact: true }).isDisabled(), true, 'View switch cannot discard an unsaved map');
    await page.getByRole('link', { name: 'Главная', exact: true }).click();
    assert.ok(page.url().endsWith('/equipment'), 'Unsaved navigation stays on map');
    failSave = false; await page.getByRole('button', { name: 'Повторить сохранение', exact: true }).click();
    await page.waitForTimeout(1000);
    conflictSave = true;
    await page.getByRole('button', { name: 'Метка', exact: true }).click(); await clickWorld(1300, 200);
    await dialog.getByLabel('Название метки').fill('Конфликт'); await dialog.getByRole('button', { name: 'Добавить' }).click();
    await page.getByRole('button', { name: 'Загрузить серверный план', exact: true }).click();
    await page.getByRole('button', { name: 'Отмена', exact: true }).click();
    assert.equal(await page.locator('.map-label').count(), 5, 'Cancel retains conflicting local edits');
    await page.getByRole('button', { name: 'Загрузить серверный план', exact: true }).click();
    conflictSave = false;
    await page.getByRole('button', { name: 'Загрузить', exact: true }).click();
    await page.waitForTimeout(300);
    assert.equal(await page.locator('.map-label').count(), 4, 'Explicit reload restores server layout');
    for (const button of await page.locator('.toast-close').all()) await button.click().catch(() => {});
    await page.screenshot({ path: 'tmp/map-editor-light.png', fullPage: true });
    await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
    await page.waitForTimeout(400);
    await page.screenshot({ path: 'tmp/map-editor-dark.png', fullPage: true });
    await page.reload();
    await page.locator('.map-wall').first().waitFor({ state: 'attached' });
    assert.equal(await page.locator('.map-wall').count(), 7);
    assert.deepEqual(await page.locator('.map-label').allTextContents(), ['Участок литья', 'А', 'Б', 'В']);
    assert.ok(Number(await page.locator('.map-equipment-card').first().getAttribute('width')) > 180);
    assert.equal(await page.locator('.map-equipment-card').count(), 2);
    await page.locator('.map-equipment-card').first().click();
    await page.getByRole('dialog', { name: 'Оборудование Станок' }).waitFor();
    await page.getByRole('button', { name: 'Закрыть', exact: true }).click();
    assert.equal(await page.locator('.map-resize-handle').count(), 0, 'Viewing must not expose editing handles');
    assert.deepEqual(errors, []);
    console.log('PASS: HTTP IDs; walls by drag/two clicks; opening; endpoint drag; placement by click; resize + undo/redo; label rename; Esc; pan/zoom; serialized saves; retry; reload; read-only preview');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
