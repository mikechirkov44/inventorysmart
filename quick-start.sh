#!/bin/bash

# ============================================
# Быстрый старт - один скрипт для всего
# ============================================

set -e

echo "========================================="
echo "  InventorySmart - Быстрый старт"
echo "========================================="
echo ""
echo "Этот скрипт:"
echo "  1. Установит Node.js, PM2, Nginx"
echo "  2. Склонирует проект"
echo "  3. Соберёт фронтенд"
echo "  4. Настроит и запустит сервер"
echo ""
read -p "Продолжить? (y/n) " -n 1 -r
echo ""

if [[ ! $REPLY =~ ^[Yy]$ ]]; then
  echo "Отменено."
  exit 1
fi

# Запуск основного деплоя
chmod +x deploy.sh
./deploy.sh

# Настройка Nginx
read -p "Настроить Nginx как reverse-proxy? (y/n) " -n 1 -r
echo ""

if [[ $REPLY =~ ^[Yy]$ ]]; then
  chmod +x setup-nginx.sh
  ./setup-nginx.sh
fi

echo ""
echo "========================================="
echo "  Готово! Приложение доступно."
echo "========================================="
